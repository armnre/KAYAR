// Builds the standalone KAYAR server: website (Vite) + all endpoints bundled into dist/server.mjs
import { build } from 'esbuild';
import { build as viteBuild } from 'vite';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const apiDir = path.join(root, 'apps/kayar/src/api');

const pkg = JSON.parse(fs.readFileSync(path.join(here, 'package.json'), 'utf8'));
let sha = process.env.SOURCE_COMMIT || '';
try { sha ||= (await import('node:child_process')).execSync('git rev-parse --short HEAD', { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { /* not a git checkout */ }
const VERSION = `${pkg.version ?? '0.0.0'}${sha ? `+${sha}` : ''}`;

const names = fs.readdirSync(apiDir).filter((f) => f.endsWith('.ts')).map((f) => f.slice(0, -3)).sort();
fs.writeFileSync(path.join(here, 'endpoints.generated.ts'),
  `// Generated by build.mjs — do not edit\n${names.map((n, i) => `import e${i} from '../apps/kayar/src/api/${n}';`).join('\n')}\nexport const endpoints = {\n${names.map((n, i) => `  ${JSON.stringify(n)}: e${i},`).join('\n')}\n};\n`);
console.log(`endpoints: ${names.length}`);

const common = {
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  sourcemap: false,
  external: ['pg-native'],
  banner: { js: "import { createRequire as __cr } from 'module'; const require = __cr(import.meta.url);" },
  alias: {
    'zitejs/db': path.join(here, 'db.ts'),
    'zitejs/backend': path.join(root, 'apps/kayar/.zite/backend.ts'),
    'zitejs/backend/base': path.join(root, 'node_modules/zitejs/dist/esm/backend/index.js'),
  },
  define: { __APP_VERSION__: JSON.stringify(VERSION) },
  logLevel: 'warning',
};
await build({ ...common, entryPoints: [path.join(here, 'server.ts')], outfile: path.join(here, 'dist/server.mjs') });
// Ops scripts (run inside the container as: node scripts/<name>.mjs)
const scripts = fs.readdirSync(path.join(here, 'scripts')).filter((f) => f.endsWith('.ts'));
await build({ ...common, entryPoints: scripts.map((f) => path.join(here, 'scripts', f)), outdir: path.join(here, 'dist/scripts'), outExtension: { '.js': '.mjs' } });
console.log(`server ${VERSION} + scripts: ${scripts.map((f) => f.replace('.ts', '.mjs')).join(', ')}`);

if (!process.argv.includes('--server-only')) { process.chdir(path.join(root, 'apps/kayar')); await viteBuild({ configFile: path.join(here, 'vite.config.ts') }); }
